function BlueCard(mode) {
	const params = {"mode": mode, "plaza": MAX_PLAZA, "corona": MAX_CORONA, "all": ALL_BLUES};
	if (params["all"] == true) delete params["all"]; //only keep the "all" param in the url if it's set to false
	if (params["mode"] === undefined) delete params["mode"]; //I want mode to come directly after seed in the url, so add it first, then if no mode was set, remove it again
	
	let str = "";
	for (let param in params) {
		str += "&" + param + "=" + params[param];
	}
	window.location = "?seed=" + (Math.floor(Math.random() * 999999) + 1) + str;
}